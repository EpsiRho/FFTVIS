using FreqFreak;
using NAudio.Wave;
using NAudio.Wave.SampleProviders;

namespace FFTVIS
{
    /// <summary>
    /// Audio file to .fvz encoder.<br></br>
    /// Create it with <see cref="EncoderOptions"/>, load audio with <see cref="LoadAudio(string)"/> or
    /// <see cref="LoadSamples"/>, call <see cref="GenerateFrames"/>, then save with <see cref="SaveToFile(string)"/>,
    /// <see cref="Save(Stream)"/> or read the result with <see cref="GetGeneratedFrames()"/>.
    /// </summary>
    public sealed class AudioEncoder
    {
        /// <summary>The settings this encoder was created with.</summary>
        public EncoderOptions Options { get; }

        /// <summary>Generated frames per channel: [channel][frame][band], after decay but before quantization.</summary>
        public double[][][] GeneratedChannels { get; private set; } = Array.Empty<double[][]>();

        /// <summary>The first channel's frames (kept for v2 callers).</summary>
        public double[][] GeneratedFrames => GeneratedChannels.Length > 0 ? GeneratedChannels[0] : Array.Empty<double[]>();

        /// <summary>The largest bar value seen while generating.</summary>
        public float MaxAmplitude { get; private set; }

        /// <summary>Frames per channel generated by the last <see cref="GenerateFrames"/>.</summary>
        public uint TotalFrames => (uint)GeneratedFrames.Length;

        public int BarCount => Options.BarCount;
        public int FPS => Options.FPS;
        public int FFTResolution => Options.FFTResolution;

        private float[][] _audio = Array.Empty<float[]>();
        private int _sampleRate;
        private double[] _bandEdges = Array.Empty<double>();

        public AudioEncoder(EncoderOptions options)
        {
            options.Validate();
            Options = options;
        }

        /// <summary>v2-style constructor. The compression bitmask maps onto v3 storage settings.</summary>
        public AudioEncoder(int barCount, double dbFloor, double dbRange,
                            double freqMin, double freqMax, int smoothness, SpectrogramMapping binMap,
                            int fftRes, int fps, CompressionType compressionType, QuantizeLevel quantLevel = QuantizeLevel.Q16)
            : this(new EncoderOptions
            {
                BarCount = barCount,
                DbFloor = dbFloor,
                DbRange = dbRange,
                FrequencyMin = freqMin,
                FrequencyMax = freqMax,
                Smoothness = smoothness,
                BinMap = binMap,
                FFTResolution = fftRes,
                FPS = fps,
                QuantizeBits = compressionType.HasFlag(CompressionType.Quantize) && quantLevel == QuantizeLevel.Q8 ? 8 : 16,
                DeltaEncode = compressionType.HasFlag(CompressionType.DeltaEncode),
                Codec = compressionType.HasFlag(CompressionType.Zstd) ? FvzCodec.Zstd : FvzCodec.None,
            })
        { }

        /// <summary>Loads an audio file (at its own sample rate, or <see cref="EncoderOptions.TargetSampleRate"/>).</summary>
        public bool LoadAudio(string path) => LoadAudio(path, Options.TargetSampleRate);

        /// <summary>Loads an audio file, resampling to <paramref name="targetSampleRate"/> unless it is 0.</summary>
        public bool LoadAudio(string path, int targetSampleRate)
        {
            if (string.IsNullOrWhiteSpace(path)) return false;
            if (targetSampleRate < 0) throw new ArgumentOutOfRangeException(nameof(targetSampleRate));
            path = path.Trim('"');

            try
            {
                using var reader = new AudioFileReader(path);
                ISampleProvider provider = reader;
                int sourceChannels = reader.WaveFormat.Channels;
                if (targetSampleRate > 0 && provider.WaveFormat.SampleRate != targetSampleRate)
                    provider = new WdlResamplingSampleProvider(provider, targetSampleRate);

                int channels = provider.WaveFormat.Channels;
                int outChannels = Options.Stereo && channels >= 2 ? 2 : 1;
                long est = (long)(reader.TotalTime.TotalSeconds * provider.WaveFormat.SampleRate) + 1024;
                var outputs = new List<float>[outChannels];
                for (int c = 0; c < outChannels; c++) outputs[c] = new List<float>((int)Math.Min(est, int.MaxValue / 2));

                var buf = new float[16384 * channels];
                int read;
                while ((read = provider.Read(buf, 0, buf.Length)) > 0)
                {
                    int frames = read / channels;
                    for (int i = 0; i < frames; i++)
                    {
                        int o = i * channels;
                        if (outChannels == 2)
                        {
                            outputs[0].Add(buf[o]);
                            outputs[1].Add(buf[o + 1]);
                        }
                        else
                        {
                            float sum = 0;
                            for (int c = 0; c < channels; c++) sum += buf[o + c];
                            outputs[0].Add(sum / channels);
                        }
                    }
                }

                _audio = outputs.Select(l => l.ToArray()).ToArray();
                _sampleRate = provider.WaveFormat.SampleRate;
                return _audio[0].Length > 0;
            }
            catch (Exception ex)
            {
                Console.Error.WriteLine($"LoadAudio failed: {ex.Message}");
                return false;
            }
        }

        /// <summary>
        /// Uses already decoded audio: one array per channel at <paramref name="sampleRate"/>. With Stereo off, several
        /// channels are mixed to mono; with Stereo on, the first two are used (a single channel stays mono).
        /// </summary>
        public bool LoadSamples(float[][] channels, int sampleRate)
        {
            if (channels.Length == 0 || channels[0].Length == 0 || sampleRate <= 0) return false;
            _sampleRate = sampleRate;
            if (Options.Stereo && channels.Length >= 2)
            {
                _audio = new[] { channels[0], channels[1] };
            }
            else if (channels.Length == 1)
            {
                _audio = new[] { channels[0] };
            }
            else
            {
                var mono = new float[channels[0].Length];
                for (int i = 0; i < mono.Length; i++)
                {
                    float sum = 0;
                    foreach (var ch in channels) sum += ch[i];
                    mono[i] = sum / channels.Length;
                }
                _audio = new[] { mono };
            }
            return true;
        }

        /// <summary>
        /// Generates frames from the loaded audio. Frame i is centred on i / FPS seconds, so it lines up with the
        /// player's clock without an offset.
        /// </summary>
        /// <param name="progress">Reports the fraction done (0-1) as frames finish.</param>
        public bool GenerateFrames(IProgress<double>? progress = null, CancellationToken cancellationToken = default)
        {
            if (_audio.Length == 0 || _audio[0].Length == 0) return false;

            int n = Options.FFTResolution;
            double hop = _sampleRate / (double)Options.FPS;
            int total = (int)Math.Ceiling(_audio[0].Length / hop);
            int channels = _audio.Length;
            var output = new double[channels][][];
            for (int c = 0; c < channels; c++) output[c] = new double[total][];

            double maxAmp = 0;
            var maxLock = new object();
            long done = 0;
            long work = (long)total * channels;
            var parallel = new ParallelOptions
            {
                MaxDegreeOfParallelism = Options.MaxThreads > 0 ? Options.MaxThreads : Environment.ProcessorCount,
                CancellationToken = cancellationToken,
            };

            Parallel.For(0, total * channels, parallel,
                () => (Builder: CreateBuilder(), Window: new float[n]),
                (job, _, local) =>
                {
                    int c = (int)(job / total);
                    int i = (int)(job % total);
                    var audio = _audio[c];
                    int start = (int)Math.Round(i * hop) - n / 2;

                    // Copy the window centred on the frame time, zero padding past either end
                    var window = local.Window;
                    Array.Clear(window);
                    int from = Math.Max(0, start);
                    int to = Math.Min(audio.Length, start + n);
                    if (to > from) Array.Copy(audio, from, window, from - start, to - from);

                    output[c][i] = local.Builder.ProcessData(window, _sampleRate) ?? new double[Options.BarCount];

                    if (progress != null)
                    {
                        long d = Interlocked.Increment(ref done);
                        if (d % 512 == 0 || d == work) progress.Report(d / (double)work);
                    }
                    return local;
                },
                local =>
                {
                    lock (maxLock) maxAmp = Math.Max(maxAmp, local.Builder._maxMagnitude);
                });

            if (Options.DecayPerSecond > 0)
                ApplyDecay(output, Options.DecayPerSecond / Options.FPS);

            _bandEdges = CreateBuilder().GetBandEdges(_sampleRate);
            MaxAmplitude = (float)maxAmp;
            GeneratedChannels = output;
            return true;
        }

        // Peak meter: rise instantly, fall at most `step` per frame.
        private static void ApplyDecay(double[][][] channels, double step)
        {
            foreach (var frames in channels)
            {
                if (frames.Length == 0) continue;
                var held = new double[frames[0].Length];
                foreach (var frame in frames)
                {
                    for (int b = 0; b < frame.Length; b++)
                    {
                        held[b] = Math.Max(frame[b], held[b] - step);
                        frame[b] = held[b];
                    }
                }
            }
        }

        /// <summary>The header describing the generated frames.</summary>
        public Metadata BuildMetadata() => new()
        {
            Version = FvzFormat.CurrentVersion,
            FftResolution = (uint)Options.FFTResolution,
            NumBands = (ushort)Options.BarCount,
            FrameRate = (ushort)Options.FPS,
            TotalFrames = TotalFrames,
            Channels = (byte)Math.Max(1, GeneratedChannels.Length),
            QuantizeBits = (byte)Options.QuantizeBits,
            Codec = Options.Codec,
            DeltaEncoded = Options.DeltaEncode,
            MaxAmplitude = MaxAmplitude,
            DecayPerSecond = (float)Options.DecayPerSecond,
            SampleRate = (uint)_sampleRate,
            Mapping = Options.BinMap,
            DbFloor = (float)Options.DbFloor,
            DbRange = (float)Options.DbRange,
            FrequencyMin = (float)Options.FrequencyMin,
            FrequencyMax = (float)(Options.FrequencyMax == -1 ? _sampleRate / 2.0 : Options.FrequencyMax),
            BandEdges = _bandEdges.Select(e => (float)e).ToArray(),
        };

        /// <summary>Writes the .fvz file to a stream.</summary>
        public bool Save(Stream output)
        {
            if (GeneratedFrames.Length == 0) return false;
            FvzFormat.Write(output, BuildMetadata(), GeneratedChannels, Options.CompressionLevel);
            return true;
        }

        /// <summary>
        /// Saves the .fvz file. Adds the .fvz extension if missing.
        /// </summary>
        public bool SaveToFile(string fileName)
        {
            if (GeneratedFrames.Length == 0) return false;
            if (!fileName.EndsWith(".fvz", StringComparison.OrdinalIgnoreCase)) fileName += ".fvz";
            using var fs = File.Create(fileName);
            return Save(fs);
        }

        /// <summary>Returns the .fvz file's bytes, positioned at the start.</summary>
        public MemoryStream SaveFileToMemory()
        {
            var ms = new MemoryStream();
            Save(ms);
            ms.Position = 0;
            return ms;
        }

        /// <summary>
        /// The generated frames as a decoded file would present them (quantized to the chosen bits), without writing
        /// and reading a file.
        /// </summary>
        public FrequencyVisualizer GetGeneratedFrames()
        {
            if (GeneratedFrames.Length == 0) return null!;
            var md = BuildMetadata();
            var codec = md.Codec;
            md.Codec = FvzCodec.None;
            var channels = FvzFormat.Unpack(md, FvzFormat.Pack(md, GeneratedChannels));
            md.Codec = codec;
            return new FrequencyVisualizer(md, channels);
        }

        private FrameBuilder CreateBuilder() => new()
        {
            FFTResolution = Options.FFTResolution,
            BarCount = Options.BarCount,
            DbFloor = Options.DbFloor,
            DbRange = Options.DbRange,
            FrequencyMin = Options.FrequencyMin,
            FrequencyMax = Options.FrequencyMax,
            Smoothness = Options.Smoothness,
            SpectrogramMapping = Options.BinMap,
        };
    }
}
